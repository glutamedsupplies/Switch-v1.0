// Validate all packs have same keys as en
for (const [code, pack] of Object.entries(packs)) {
  const missing = Object.keys(en).filter((k) => !(k in pack));
  const extra = Object.keys(pack).filter((k) => !(k in en));
  if (missing.length || extra.length) {
    console.error(code, { missing, extra });
    process.exit(1);
  }
}

function serializePack(obj, indent = 2) {
  const pad = " ".repeat(indent);
  const lines = Object.entries(obj).map(([k, v]) => `${pad}"${k}": ${JSON.stringify(v)},`);
  // drop trailing comma on last? keep for consistency with existing style - actually trailing commas OK in modern JS
  return lines.join("\n");
}

const order = ["en", "zh", "es", "hi", "ar", "fr", "pt", "ru", "ja", "de", "ko", "vi", "id", "tl", "th"];
const body = order
  .map((code) => `  ${code}: {\n${serializePack(packs[code], 4)}\n  }`)
  .join(",\n");

const replacement = `const loginTranslations = {\n${body},\n};`;

const loginJsPath = path.join(__dirname, "..", "backend", "public", "login.js");
