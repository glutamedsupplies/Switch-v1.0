const start = loginJs.indexOf("const loginTranslations = {");
const endMarker = "\n};\n\nfunction t(";
const end = loginJs.indexOf(endMarker, start);
if (start < 0 || end < 0) {
  console.error("Could not locate loginTranslations block");
  process.exit(1);
}
loginJs = loginJs.slice(0, start) + replacement + "\n\nfunction t(" + loginJs.slice(end + endMarker.length);
fs.writeFileSync(loginJsPath, loginJs);
