  static String normalize(String? code) {
    final raw = (code ?? '').trim().toLowerCase();
    if (strings.containsKey(raw)) {
      return raw;
    }
    if (raw.startsWith('zh')) {
      return 'zh';
    }
    if (raw.startsWith('tl') || raw.startsWith('fil')) {
      return 'tl';
    }
    return 'en';
  }

  static String labelFor(String code) {
    final normalized = normalize(code);
    for (final option in options) {
      if (option.code == normalized) {
        return option.label;
      }
    }
    return 'English';
  }

  static String t(String languageCode, String key) {
    final lang = normalize(languageCode);
    return strings[lang]?[key] ?? strings['en']![key] ?? key;
  }
